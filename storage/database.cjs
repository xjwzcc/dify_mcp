'use strict';
const { DatabaseSync } = require('node:sqlite');
const { FeishuJournal } = require('./feishu.cjs');
const quote = name => '"' + name.replaceAll('"', '""') + '"';
function snapshot(db) {
  const tables = db.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
  const hasSequence = db.prepare("SELECT 1 FROM sqlite_master WHERE name='sqlite_sequence'").get();
  return tables.map(table => ({ ...table,
    sequence: hasSequence ? db.prepare('SELECT seq FROM sqlite_sequence WHERE name=?').get(table.name)?.seq : undefined,
    rows: db.prepare(`SELECT rowid AS __storage_rowid, * FROM ${quote(table.name)}`).all() }));
}
function restoreSnapshot(db, tables) {
  if (!Array.isArray(tables)) throw Error('Invalid snapshot');
  db.exec('BEGIN');
  try {
    for (const table of tables) {
      // The encrypted snapshot is generated by this application, never from browser input.
      if (!/^[a-z_]+$/.test(table.name) || !table.sql.startsWith('CREATE TABLE')) throw Error('Invalid snapshot table');
      db.exec(table.sql);
      for (const row of table.rows) {
        const names = Object.keys(row);
        db.prepare(`INSERT INTO ${quote(table.name)} (${names.map(name => name === '__storage_rowid' ? 'rowid' : quote(name)).join(',')}) VALUES (${names.map(() => '?').join(',')})`)
          .run(...names.map(name => row[name]));
      }
      if (table.sequence !== undefined) {
        db.prepare('DELETE FROM sqlite_sequence WHERE name=?').run(table.name);
        db.prepare('INSERT INTO sqlite_sequence(name,seq) VALUES(?,?)').run(table.name, table.sequence);
      }
    }
    db.exec('COMMIT');
  } catch (error) { db.exec('ROLLBACK'); throw error; }
}
async function openDatabase(namespace, filename, env = process.env) {
  const mode = env.STORAGE_BACKEND || 'nas';
  if (!['nas', 'feishu'].includes(mode)) throw Error('Invalid STORAGE_BACKEND');
  const journal = mode === 'feishu' ? new FeishuJournal(namespace, env) : null;
  const db = new DatabaseSync(journal ? ':memory:' : filename);
  let poisoned = false, queue = Promise.resolve(), pending = 0, hooks = null, schema;
  if (journal) {
    try {
      for (const commit of await journal.restore()) {
        if (commit.kind === 'snapshot') restoreSnapshot(db, commit.data);
        else if (!db.applyChangeset(Buffer.from(commit.data, 'base64'))) throw Error('Recovery changeset conflict');
      }
      schema = db.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
    } catch (error) { db.close(); throw error; }
  }
  const storage = {
    db, mode,
    get busy() { return hooks !== null; },
    get healthy() { return !poisoned; },
    afterCommit(fn) { if (hooks) hooks.push(fn); else fn(); },
    async ready() {
      if (!journal) return;
      const current = db.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
      if (!journal.head.id) await journal.append('snapshot', snapshot(db));
      else if (JSON.stringify(schema) !== JSON.stringify(current)) throw Error('Feishu schema migration requires an explicit offline migration');
    },
    wrap(handler) {
      if (!journal) return handler;
      return (req, res) => {
        if (poisoned || pending >= 100) return unavailable(res);
        pending++;
        const task = queue.then(async () => {
          if (poisoned) return unavailable(res);
          if (req.destroyed || res.destroyed) return;
          if (['GET', 'HEAD', 'OPTIONS'].includes(req.method)) return handler(req, res);
          const session = db.createSession();
          const writeHead = res.writeHead, end = res.end;
          let status = 200, headers = {}, output, ended = false;
          res.writeHead = function(code, values) { status = code; headers = values || {}; return this; };
          res.end = function(value) { output = value; ended = true; return this; };
          db.exec('SAVEPOINT durable_request');
          hooks = [];
          try {
            // Expiry is persisted as part of the next request, never by a timer outside the transaction.
            if (db.prepare("SELECT 1 FROM sqlite_master WHERE name='sessions'").get())
              db.prepare('DELETE FROM sessions WHERE expires<?').run(Date.now());
            await handler(req, res);
            if (!ended) throw Error('Mutating route must return a buffered response');
            if (status >= 400) {
              db.exec('ROLLBACK TO durable_request; RELEASE durable_request');
              hooks = null;
            } else {
              const changes = session.changeset();
              if (changes.byteLength) {
                const checkpoint = (journal.head.seq + 1) % journal.checkpointEvery === 0;
                try { await journal.append(checkpoint ? 'snapshot' : 'changeset', checkpoint ? snapshot(db) : Buffer.from(changes).toString('base64')); }
                catch (error) { poisoned = true; throw error; }
              }
              db.exec('RELEASE durable_request');
              const callbacks = hooks; hooks = null;
              for (const callback of callbacks) callback();
            }
            res.writeHead = writeHead; res.end = end;
            res.writeHead(status, headers); res.end(output);
          } catch (error) {
            try { db.exec('ROLLBACK TO durable_request; RELEASE durable_request'); } catch { poisoned = true; }
            hooks = null;
            res.writeHead = writeHead; res.end = end;
            // Never expose API responses, credentials or a local success after persistence failure.
            console.error('Durable storage request failed:', error.message);
            unavailable(res);
          } finally { session.close(); }
        }).catch(error => {
          poisoned = true;
          console.error('Storage queue failed:', error.message);
          unavailable(res);
        }).finally(() => pending--);
        queue = task;
      };
    }
  };
  return storage;
}
function unavailable(res) {
  if (res.destroyed || res.writableEnded) return;
  res.removeHeader('Set-Cookie');
  res.writeHead(503, { 'Content-Type': 'application/json; charset=utf-8', 'Cache-Control': 'no-store', 'Retry-After': '5' });
  res.end(JSON.stringify({ error: '云端保存尚未确认，请保留当前页面并联系管理员恢复服务；不要重复提交。' }));
}
module.exports = { openDatabase, snapshot, restoreSnapshot };
